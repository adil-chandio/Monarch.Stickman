#!/usr/bin/env python3
"""tighten.py — rebuild the narration timing so the voice flows.

The TTS clips each carried ~0.6 s of dead air at the head/tail plus long pauses
between sentences, and the old timeline spaced beats by the *untrimmed* mp3
length. That is why the voiceover had holes in the middle of the flow.

This script
  1. trims every clip to speech,
  2. squeezes internal pauses (>0.34 s) down to 0.18 s with click-free cuts,
  3. writes the tightened audio to audio_v4/,
  4. regenerates timeline_v4.py with real durations and sentence-accurate cues.
"""
import os, json, subprocess
import numpy as np
import soundfile as sf
from scipy import signal

import audio_v3 as A
from timeline_v3 import BEATS as OLD

ROOT = os.path.dirname(os.path.abspath(__file__))
OUTD = os.path.join(ROOT, "audio_v4")
os.makedirs(OUTD, exist_ok=True)
SR = A.SR

MIN_SIL = 0.34      # pauses longer than this get shortened
KEEP = 0.18         # ... to this
EDGE = .012         # fade in/out at every edit


def envelope(x, win=.02):
    w = int(win * SR)
    e = np.abs(x)
    return np.array([e[i:i + w].max() for i in range(0, len(e) - w, w)]), w


def speech_bounds(x):
    e, w = envelope(x)
    thr = max(1e-4, e.max() * .006)
    idx = np.where(e > thr)[0]
    a = max(0, idx[0] * w - int(.01 * SR))
    b = min(len(x), idx[-1] * w + int(.03 * SR))
    return a, b


def pauses(x):
    """list of (start_sample, len_samples) for silent runs >= MIN_SIL"""
    e, w = envelope(x)
    thr = max(1e-4, e.max() * .012)
    sil = e < thr
    runs, i = [], 0
    while i < len(sil):
        if sil[i]:
            j = i
            while j < len(sil) and sil[j]:
                j += 1
            if (j - i) * w >= MIN_SIL * SR:
                runs.append((i * w, (j - i) * w))
            i = j
        else:
            i += 1
    return runs


def tighten(x):
    """trim + squeeze long internal pauses; returns (y, boundaries_in_samples)"""
    a, b = speech_bounds(x.mean(axis=1) if x.ndim == 2 else x)
    x = x[a:b].copy()
    mono = x.mean(axis=1) if x.ndim == 2 else x
    keep = int(KEEP * SR)
    segs, bounds, pos = [], [], 0
    for st, ln in pauses(mono):
        if st < pos:
            continue
        segs.append((pos, min(len(x), st + keep)))
        pos = min(len(x), st + ln)
        bounds.append(sum(e - s for s, e in segs))
    segs.append((pos, len(x)))
    parts = []
    for i, (s, e) in enumerate(segs):
        p = x[s:e].copy()
        f = min(int(EDGE * SR), max(1, len(p) // 3))
        if i > 0 and f > 2:
            p[:f] *= np.linspace(0, 1, f)[:, None]
        if i < len(segs) - 1 and f > 2:
            p[-f:] *= np.linspace(1, 0, f)[:, None]
        parts.append(p)
    y = np.concatenate(parts, axis=0).astype(np.float32)
    f = min(int(EDGE * SR), len(y) // 4)
    y[:f] *= np.linspace(0, 1, f)[:, None]
    y[-f:] *= np.linspace(1, 0, f)[:, None]
    return y, bounds


def cue_times(tight_len, bounds, cues):
    """map cue k to the k-th pause (tightened time), else split by text length"""
    n = len(cues)
    k = n - 1
    if len(bounds) >= k and k >= 0:
        picks = bounds[:k]
        ts = [0.05] + [max(.05, b / SR - .08) for b in picks]
    else:
        w = [max(6, len(c.replace(" ", ""))) for c, _ in cues]
        tot = sum(w)
        acc, ts = 0.0, []
        for wg in w:
            ts.append(0.05 + acc / tot * max(.30, tight_len - .10))
            acc += wg
    return ts


LEAD, GAP, TAIL = 0.30, 0.32, 1.60


def main():
    rows, t = [], LEAD
    for b in OLD:
        src = b["audio"]
        clip = A.decode(src).astype(np.float32)
        y, bounds = tighten(clip)
        dst = os.path.join(OUTD, f"beat{b['n']:02d}.wav")
        sf.write(dst, y, SR, subtype="FLOAT")
        dur = len(y) / SR
        ts = cue_times(dur, bounds, b["cues"])
        rows.append(dict(n=b["n"], kind=b["kind"], trans=b["trans"], cues=b["cues"],
                         audio=dst, start=round(t, 3), dur=round(dur, 3),
                         cue_ts=[round(x, 3) for x in ts]))
        t += dur + GAP
    total = round((t - GAP) + TAIL, 3)

    lines = ['#!/usr/bin/env python3',
             '"""Timeline v4 - generated by tighten.py: real speech lengths, sentence-accurate cues."""',
             'import os', '',
             'ROOT = os.path.dirname(os.path.abspath(__file__))', '',
             'BEATS = [']
    for r in rows:
        lines.append(f'    dict(n={r["n"]}, kind="{r["kind"]}", trans="{r["trans"]}",')
        lines.append(f'         start={r["start"]}, dur={r["dur"]}, audio=os.path.join(ROOT, "audio_v4", "{os.path.basename(r["audio"])}"),')
        lines.append('         cues=[')
        for c, kw in r["cues"]:
            lines.append(f'             ({c!r}, {kw!r}),')
        lines.append('         ],')
        lines.append(f'         cue_ts={r["cue_ts"]}),')
    lines.append(']')
    lines.append('')
    lines.append('for _b in BEATS:')
    lines.append('    _b["cue_times"] = [dict(text=t, kw=k, t=x) for (t, k), x in zip(_b["cues"], _b["cue_ts"])]')
    lines.append('')
    lines.append(f'TOTAL = {total}')
    lines.append('')
    open(os.path.join(ROOT, "timeline_v4.py"), "w").write("\n".join(lines))

    print(f"{'bt':>3} {'dur':>6} {'start':>7} {'cues':>4}")
    for r in rows:
        print(f"{r['n']:>3} {r['dur']:6.2f} {r['start']:7.2f} {len(r['cues']):>4}")
    print(f"TOTAL {total:.2f}s")


if __name__ == "__main__":
    main()
